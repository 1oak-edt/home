export interface GeoPoint {
  lon: number;
  lat: number;
  precision: "city" | "state" | "none";
}

export function geocode(city: string | null, state: string | null): GeoPoint | null {
  const st = state?.trim().toUpperCase() ?? "";
  if (city) {
    const key = `${city.trim().toLowerCase()}|${st}`;
    const hit = CITY_COORDS[key];
    if (hit) return { lon: hit[0], lat: hit[1], precision: "city" };
  }
  const stateHit = STATE_CENTROIDS[st];
  if (stateHit) return { lon: stateHit[0], lat: stateHit[1], precision: "state" };
  return null;
}

// Small deterministic offset so multiple deals in the same city/state don't stack exactly.
export function jitter(id: string, magnitude = 0.35): [number, number] {
  let hash = 0;
  for (let i = 0; i < id.length; i++) hash = (hash * 31 + id.charCodeAt(i)) >>> 0;
  const a = ((hash % 1000) / 1000) * Math.PI * 2;
  const r = (((hash >> 10) % 1000) / 1000) * magnitude;
  return [Math.cos(a) * r, Math.sin(a) * r];
}
